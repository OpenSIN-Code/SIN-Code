func TestUndercoverMode_ConcurrentToggle(t *testing.T) {
	u := NewUndercoverMode()
	var wg sync.WaitGroup
	onCount := atomic.Int64{}
	const n = 100
	for i := 0; i < n; i++ {
		wg.Add(1)
		go func() {
			defer wg.Done()
			if u.Toggle() {
				onCount.Add(1)
			}
		}()
	}
	wg.Wait()
	final := u.Enabled()
	sum := onCount.Load()
	if final && sum%2 == 0 {
		t.Errorf("final=on but even number of toggles returned true: %d", sum)
	}
	if !final && sum%2 != 0 {
		t.Errorf("final=off but odd number of toggles returned true: %d", sum)
	}
}

