func TestUndercoverFilter_TrimsTrailingWhitespace(t *testing.T) {
	u := NewUndercoverMode()
	msg := "fix: thing   \n\nCo-Authored-By: AI <a@b.c>\n  \n"
	out := u.FilterCommitMessage(msg)
	if strings.Contains(out, "   ") {
		t.Errorf("trailing whitespace not trimmed: %q", out)
	}
	for _, ln := range strings.Split(out, "\n") {
		if ln != strings.TrimRight(ln, " \t") {
			t.Errorf("line has trailing whitespace: %q", ln)
		}
	}
}

