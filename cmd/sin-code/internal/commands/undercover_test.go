func newUndercoverSession(t *testing.T) *session.Session {
	t.Helper()
	store, err := session.Open(filepath.Join(t.TempDir(), "uc.db"))
	if err != nil {
		t.Fatalf("open store: %v", err)
	}
	t.Cleanup(func() { store.Close() })
	sess, err := store.StartOrResume("")
	if err != nil {
		t.Fatalf("start session: %v", err)
	}
	return sess
}

func TestUndercoverMode_EnableDisableToggle(t *testing.T) {
	u := NewUndercoverMode()
	if u.Enabled() {
		t.Fatal("default should be disabled")
	}
	u.Enable()
	if !u.Enabled() {
		t.Error("Enable failed")
	}
	u.Disable()
	if u.Enabled() {
		t.Error("Disable failed")
	}
	if got := u.Toggle(); !got {
		t.Error("Toggle from disabled should return true (new state on)")
	}
	if !u.Enabled() {
		t.Error("Toggle failed to enable")
	}
	if got := u.Toggle(); got {
		t.Error("Toggle from enabled should return false (new state off)")
	}
	if u.Enabled() {
		t.Error("Toggle failed to disable")
	}
}

