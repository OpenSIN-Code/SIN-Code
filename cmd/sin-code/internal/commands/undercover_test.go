func TestRegistry_Dispatch(t *testing.T) {
	r := NewRegistry()
	r.Register(NewUndercoverCommand(NewUndercoverMode()))
	sess := newUndercoverSession(t)
	handled, out, err := r.Dispatch(context.Background(), "/undercover on", sess)
	if !handled {
		t.Error("should be handled")
	}
	if err != nil {
		t.Errorf("err: %v", err)
	}
	if !strings.Contains(out, "ON") {
		t.Errorf("out: %q", out)
	}
	handled, _, _ = r.Dispatch(context.Background(), "not a slash", sess)
	if handled {
		t.Error("non-slash line should not be handled")
	}
	handled, _, _ = r.Dispatch(context.Background(), "/unknown", sess)
	if handled {
		t.Error("unknown slash should not be handled by this registry")
	}
}

