// temp Go source tree, parses it with go/parser, and checks that
// matching / non-matching signatures are reported correctly.
// Docs: docs/SPEC-LAYER.md §"Drift detection (the hardening)"
package spec

import (
	"os"
	"path/filepath"
	"strings"
	"testing"
)

// writeGoFile is a tiny helper that writes a Go file under dir/name.
func writeGoFile(t *testing.T, dir, name, body string) {
	t.Helper()
	if err := os.WriteFile(filepath.Join(dir, name), []byte(body), 0o644); err != nil {
		t.Fatal(err)
	}
}

func TestDrift_AllMatch(t *testing.T) {
	root := t.TempDir()
	writeGoFile(t, root, "a.go", `package x

func Foo(x int, y string) error { return nil }
func Bar()                     {}
`)

	s := &Spec{
		Title: "demo",
		Requirements: []Requirement{
			{ID: "R1", Text: "`Foo(x int, y string) error` is in the public API", Priority: Must},
			{ID: "R2", Text: "`Bar()` is in the public API", Priority: Must},
		},
	}
	rep, err := s.DetectSignatureDrift(root)
	if err != nil {
		t.Fatalf("DetectSignatureDrift: %v", err)
	}
	if len(rep.Hits) != 2 {
		t.Fatalf("expected 2 hits, got %d", len(rep.Hits))
	}
	for _, h := range rep.Hits {
		if !h.Match {
			t.Errorf("%s: expected match, got drift: %s", h.RequirementID, h.Note)
		}
	}
	if rep.HasFailures() {
		t.Fatal("HasFailures should be false")
	}
}

func TestDrift_ParamMismatch(t *testing.T) {
	root := t.TempDir()
	writeGoFile(t, root, "a.go", `package x

func Foo(x int) error { return nil }
`)

	s := &Spec{
		Title: "demo",
		Requirements: []Requirement{
			{ID: "R1", Text: "`Foo(x string) error` is in the public API", Priority: Must},
		},
	}
	rep, _ := s.DetectSignatureDrift(root)
	if len(rep.Hits) != 1 {
		t.Fatalf("expected 1 hit, got %d", len(rep.Hits))
	}
	if rep.Hits[0].Match {
		t.Fatal("expected drift (param type differs)")
	}
	if !strings.Contains(rep.Hits[0].Note, "drift") {
		t.Fatalf("expected drift note, got: %q", rep.Hits[0].Note)
	}
	if !rep.HasFailures() {
		t.Fatal("HasFailures should be true")
	}
}

